using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;
using QualityControl.Application.Common.Interfaces;
using QualityControl.Application.Common.Options;

namespace QualityControl.Infrastructure.Services;

/// <summary>
/// Stores uploads on the local disk under a configured root.
/// </summary>
/// <remarks>
/// Suitable for a single application server, which is how this system is deployed
/// on-premises. Behind a load balancer the root must be shared storage, or this
/// class replaced with an object-storage implementation — the interface is the
/// seam that makes that a one-class change.
/// </remarks>
public class FileStorageService : IFileStorageService
{
    private readonly string _rootPath;
    private readonly ILogger<FileStorageService> _logger;

    public FileStorageService(
        IOptions<FileStorageOptions> options,
        IHostEnvironment environment,
        ILogger<FileStorageService> logger)
    {
        _logger = logger;

        var configured = options.Value.RootPath;

        _rootPath = Path.IsPathRooted(configured)
            ? configured
            : Path.Combine(environment.ContentRootPath, configured);

        Directory.CreateDirectory(_rootPath);
    }

    public async Task<string> SaveAsync(
        Stream content,
        string originalFileName,
        string folder,
        CancellationToken cancellationToken = default)
    {
        var directory = ResolveFolder(folder);
        Directory.CreateDirectory(directory);

        // The name is generated, never derived from the upload. A client-supplied
        // name could traverse directories, collide with an existing file, or land
        // as something the web server would treat as executable.
        var extension = Path.GetExtension(originalFileName).ToLowerInvariant();
        var storedFileName = $"{Guid.NewGuid():N}{extension}";
        var fullPath = Path.Combine(directory, storedFileName);

        await using var target = new FileStream(
            fullPath,
            FileMode.CreateNew,
            FileAccess.Write,
            FileShare.None,
            bufferSize: 81920,
            useAsync: true);

        await content.CopyToAsync(target, cancellationToken);

        _logger.LogInformation("Файл сохранён: {Folder}/{StoredFileName}", folder, storedFileName);

        return storedFileName;
    }

    public Task<Stream?> OpenReadAsync(
        string storedFileName,
        string folder,
        CancellationToken cancellationToken = default)
    {
        var fullPath = ResolveFilePath(storedFileName, folder);

        if (!File.Exists(fullPath))
        {
            return Task.FromResult<Stream?>(null);
        }

        Stream stream = new FileStream(
            fullPath,
            FileMode.Open,
            FileAccess.Read,
            FileShare.Read,
            bufferSize: 81920,
            useAsync: true);

        return Task.FromResult<Stream?>(stream);
    }

    public Task DeleteAsync(string storedFileName, string folder, CancellationToken cancellationToken = default)
    {
        var fullPath = ResolveFilePath(storedFileName, folder);

        if (File.Exists(fullPath))
        {
            File.Delete(fullPath);
            _logger.LogInformation("Файл удалён: {Folder}/{StoredFileName}", folder, storedFileName);
        }

        return Task.CompletedTask;
    }

    public bool Exists(string storedFileName, string folder) =>
        File.Exists(ResolveFilePath(storedFileName, folder));

    private string ResolveFolder(string folder) => Path.Combine(_rootPath, folder);

    /// <summary>
    /// Builds the full path and proves it stays inside the storage root.
    /// </summary>
    /// <remarks>
    /// Names come from the database and are generated by <see cref="SaveAsync"/>, so
    /// they should already be safe. This checks anyway: the cost is one string
    /// comparison, and the failure it prevents is reading arbitrary files off the
    /// server if a name is ever tampered with or built by future code.
    /// </remarks>
    private string ResolveFilePath(string storedFileName, string folder)
    {
        var fileName = Path.GetFileName(storedFileName);
        var directory = ResolveFolder(folder);
        var fullPath = Path.GetFullPath(Path.Combine(directory, fileName));
        var rootFullPath = Path.GetFullPath(_rootPath);

        if (!fullPath.StartsWith(rootFullPath, StringComparison.OrdinalIgnoreCase))
        {
            _logger.LogError(
                "Попытка обращения к файлу за пределами хранилища: {StoredFileName}",
                storedFileName);

            throw new UnauthorizedAccessException("Обращение за пределы хранилища файлов запрещено.");
        }

        return fullPath;
    }
}
